export type ClosedBlock = 'RIASEC' | 'PERSONALITY_16' | 'GERCHIKOV' | 'PINK';
export type SeedScaleType = 'LIKERT_5' | 'RIASEC_4';

export interface SeedQuestion {
  block: ClosedBlock;
  scaleKey: string;
  orderIndex: number;
  isReverse: boolean;
  scaleType: SeedScaleType;
  text: string;
}

const riasec = (scaleKey: string, texts: string[]): SeedQuestion[] =>
  texts.map((text, i) => ({
    block: 'RIASEC',
    scaleKey,
    orderIndex: i + 1,
    isReverse: false,
    scaleType: 'RIASEC_4',
    text,
  }));

// reverseIndex — 1-based номер реверсивного вопроса внутри блока (или null).
const likert = (
  block: ClosedBlock,
  scaleKey: string,
  texts: string[],
  reverseIndex: number | null,
): SeedQuestion[] =>
  texts.map((text, i) => ({
    block,
    scaleKey,
    orderIndex: i + 1,
    isReverse: reverseIndex === i + 1,
    scaleType: 'LIKERT_5',
    text,
  }));

